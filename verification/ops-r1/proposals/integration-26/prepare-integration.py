"""Pin integration scope and, only after formatting drift, reuse the bounded adapter."""
import csv
import hashlib
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
OUT = Path(sys.argv[1]).resolve()
ACCEPTED = '75d63dfb564a4f860c637160ec1d2bbbc8fcc89823cba06bbbfbae25dc71ab4c'
BASE = '0dd8d7503af3116241ad7c1e23c293b1d5849cc1'
sha = lambda data: hashlib.sha256(data).hexdigest()
head = subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=ROOT).decode().strip()
execution = ROOT / 'verification/ops-r1/proposals/shared-acquisition/execution'
manifest = json.loads((execution / 'reviewed-green-performance-25-root-sources.json').read_bytes())
tracked = subprocess.check_output(['git', 'ls-files', '-z', '--', 'src', 'Cargo.toml', 'Cargo.lock', 'build.rs', '.cargo'], cwd=ROOT).decode().split('\0')
names = sorted(set(filter(None, tracked)) | {row['path'] for row in manifest['files']})
rows = []
for name in names:
    data = (ROOT / name).read_bytes()
    if Path(name).suffix in ('.rs', '.toml') or name == 'Cargo.lock':
        data = data.replace(b'\r\n', b'\n')
    rows.append({'path': name, 'sha256': sha(data)})
source = sha(json.dumps(rows, separators=(',', ':')).encode())
files = subprocess.check_output(['git', 'diff', '--name-only', BASE, '--'], cwd=ROOT).decode().splitlines()
untracked = subprocess.check_output(['git', 'ls-files', '--others', '--exclude-standard'], cwd=ROOT).decode().splitlines()
files = sorted(set(files + untracked))
categories = {}
with (OUT / 'integration-files.csv').open('w', newline='', encoding='utf-8') as stream:
    writer = csv.writer(stream)
    writer.writerow(['path', 'scope', 'sha256_or_deleted'])
    for name in files:
        if name.startswith('src/tests/'):
            category = 'tracked regression or diagnostic test'
        elif name.startswith('src/'):
            category = 'shared acquisition lifecycle or test-only observations'
        elif name.startswith('verification/'):
            category = 'historical evidence and reusable operator definitions'
        elif name.startswith('docs/'):
            category = 'mission evidence or governance candidate'
        elif name in ['AGENTS.md', 'scripts/check-file-sizes.ps1', 'scripts/tests/check-file-sizes.tests.ps1']:
            category = 'separately owner-authorized verification size exemption'
        elif name in ['.gitignore', '.gitattributes']:
            category = 'verification bytecode cleanup and exact-byte checkout fidelity'
        else:
            raise ValueError('Unclassified integration path: ' + name)
        path = ROOT / name
        assert path.suffix != '.pyc' or not path.exists(), 'Generated bytecode remains in candidate'
        writer.writerow([name, category, sha(path.read_bytes()) if path.exists() else 'DELETED'])
        categories[category] = categories.get(category, 0) + 1
record = {'head': head, 'comparison_base': BASE, 'accepted_source_sha256': ACCEPTED,
          'source_tree_sha256': source, 'source_changed': source != ACCEPTED,
          'categories': categories, 'scope_csv_sha256': sha((OUT / 'integration-files.csv').read_bytes())}
if source != ACCEPTED:
    target = Path(__file__).resolve().parent / 'execution'
    target.mkdir(exist_ok=True)
    pin = target / 'reviewed-green-integration-26-sources.json'
    assert not pin.exists(), 'Preserve prior candidate pins; do not overwrite'
    manifest['standing'] = 'Integration formatting successor; historical source identities remain unchanged'
    manifest['candidate_source_tree_sha256'] = source
    pin.write_text(json.dumps(manifest, indent=2) + '\n', encoding='utf-8')
    original = (execution / 'capture.py').read_text(encoding='utf-8')
    text = original.replace("SOURCE_PINS={", "SOURCE_PINS={'green-integration-26': '" + sha(pin.read_bytes()) + "', ", 1)
    text = text.replace("'performance-25-root'):", "'performance-25-root','integration-26'):", 1)
    text = text.replace("    proposal=pathlib", "        if amendment=='integration-26':source_key='green-integration-26'\n    proposal=pathlib", 1)
    text = text.replace("source_key=='green-performance-25-root'", "source_key in ('green-performance-25-root','green-integration-26')")
    text = text.replace("head!='" + BASE + "'", "head!='" + head + "'")
    (target / 'capture.py').write_text(text, encoding='utf-8')
    (target / 'invoke-build-capture.ps1').write_bytes((execution / 'invoke-build-capture.ps1').read_bytes())
    record['execution'] = str(target)
(OUT / 'integration-source.json').write_text(json.dumps(record, indent=2) + '\n', encoding='utf-8')
print(json.dumps(record, indent=2))
